def _plots(out_dir: Path, report: dict[str, Any], obs: list[dict[str, Any]]) -> list[str]:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return []
    written = []
    hist = report["historical_synthetic"]["category"]
    fig, ax = plt.subplots(figsize=(7, 3.5))
    ax.bar(list(hist), [v["median_h"] for v in hist.values()], color="#8c8c8c")
    ax.set_ylabel("median hours")
    ax.set_title("Historical resolution time by category (SYNTHETIC)")
    ax.tick_params(axis="x", labelsize=8)
    fig.tight_layout()
    fig.savefig(out_dir / "mttr_historical.png", dpi=130)
    plt.close(fig)
    written.append("mttr_historical.png")
    if obs:
        fig, ax = plt.subplots(figsize=(5, 4))
        data = [[o["ttd_s"] for o in obs if o["mode"] == m] for m in ("manual", "assisted")]
        ax.boxplot(data, tick_labels=["manual", "assisted"])
        ax.set_ylabel("time to decision (s)")
        ax.set_title("Trial TTD by mode")
        fig.tight_layout()
        fig.savefig(out_dir / "mttr_ttd.png", dpi=130)
        plt.close(fig)
        corr = report["trial"]["correctness"]
        keys = ["category", "subcategory", "priority_within_one", "kb_or_escalation", "all"]
        fig, ax = plt.subplots(figsize=(7, 3.5))
        for i, m in enumerate(("manual", "assisted")):
            ax.bar(
                [j + i * 0.4 for j in range(len(keys))],
                [corr[m][k] or 0 for k in keys],
                0.4,
                label=m,
            )
        ax.set_xticks([j + 0.2 for j in range(len(keys))], keys, fontsize=8)
        ax.set_ylim(0, 1)
        ax.set_title("Trial decision correctness")
        ax.legend()
        fig.tight_layout()
        fig.savefig(out_dir / "mttr_correctness.png", dpi=130)
        plt.close(fig)
        written += ["mttr_ttd.png", "mttr_correctness.png"]
    return written


def build_report(
    *,
    root: Path | None = None,
    events_path: Path | None = None,
    db_path: Path | None = None,
    out_dir: Path | None = None,
    plots: bool = True,
) -> dict[str, Any]:
    from ingest.make_seed import load_seed

    base = root or ROOT
    events_path = events_path or repo_path("trial_raw_events", root)
    db_path = db_path or repo_path("app_db", root)
    out_dir = out_dir or base / data_config()["paths"]["eval_out"]
    out_dir.mkdir(parents=True, exist_ok=True)
    gold = read_json(repo_path("trial_gold", root))
    incident_kbs = {r.ticket_id: set(r.metadata.get("kb_ids") or []) for r in load_seed(root)}

    obs: list[dict[str, Any]] = []
    if events_path.exists():
        obs = observations(read_events(events_path), set(gold))
        trial = (
            trial_summary(obs, gold, incident_kbs)
            if obs
            else {"status": "raw_events.csv has no complete trial observations"}
        )
    else:
        shown = events_path.relative_to(base) if events_path.is_relative_to(base) else events_path
        trial = {
            "status": "no_trial_data",
            "note": f"{shown} not found: run the trial (trial/protocol.md) and "
            "`make trial-export` first",
        }
    report = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "trial": trial,
        "live": live_metrics(db_path),
        "historical_synthetic": historical_baseline(root),
        "caveats": CAVEATS,
    }
    if plots:
        report["charts"] = _plots(out_dir, report, obs)
    (out_dir / "mttr.json").write_text(json.dumps(report, indent=2, default=str) + "\n")
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--events", type=Path, default=None, help="raw_events.csv path")
    parser.add_argument("--db", type=Path, default=None, help="app.db path")
    parser.add_argument("--no-plots", action="store_true")
    args = parser.parse_args(argv)
    r = build_report(events_path=args.events, db_path=args.db, plots=not args.no_plots)
    t = r["trial"]
    if t.get("status") == "ok":
        print(
            json.dumps(
                {
                    "participants": t["participants"],
                    "observations": t["observations"],
                    "median_ttd_manual_s": t["ttd"]["manual"]["median_s"],
                    "median_ttd_assisted_s": t["ttd"]["assisted"]["median_s"],
                    "median_ttd_change_pct": t["median_ttd_change_pct"],
                    "all_correct": {m: t["correctness"][m]["all"] for m in ("manual", "assisted")},
                },
                indent=2,
            )
        )
    else:
        print(f"trial: {t['status']}; live: {r['live']['status']}; wrote eval/out/mttr.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
