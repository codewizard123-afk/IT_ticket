"""``python -m eval.mttr_report`` (``make mttr-report``) — FR-09 MTTR analysis (architecture
§8.10, §9.3, §14.2; P1-T8).

Inputs (all optional; whatever exists is reported, nothing is invented):

* ``trial/results/raw_events.csv`` — P4's trial export (``trial/export.py``): one row per event,
  decision columns filled on ``decision.submitted`` / ``manual.decision`` rows.
* ``data/test/trial_gold.json`` — gold answers for T01…T12 (never shown in the UI).
* ``data/app.db`` → ``ticket_events`` — live TTR / MTTR from the running app (P3).
* ``data/processed/tickets_enriched.json`` — the **synthetic** historical baseline (context only).

Outputs: ``eval/out/mttr.json`` + ``mttr_ttd.png``, ``mttr_correctness.png``,
``mttr_historical.png``.

TTD (time to decision): assisted = ``decision.submitted − ui.viewed``; manual =
``manual.decision − manual.started``, per participant × ticket. Correctness vs gold: category ✓,
subcategory ✓, priority within ±1 level, and the right KB article (or a curated incident linked
to it) **or** an escalation when gold says escalate.
"""

from __future__ import annotations

import argparse
import csv
import json
import sqlite3
import statistics
from collections import defaultdict
from collections.abc import Iterable, Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from eval import metrics as M
from shared.constants import PRIORITY_LEVEL, PRIORITY_LEVELS
from store.config import ROOT, data_config, read_json, repo_path

START_EVENT = {"assisted": "ui.viewed", "manual": "manual.started"}
END_EVENT = {"assisted": "decision.submitted", "manual": "manual.decision"}
CAVEATS = [
    "Small sample (target >= 4 participants x 12 tickets): the result is indicative, not "
    "statistically significant.",
    "Participants are partly the builders of the system: expect learning and expectation "
    "effects. The crossover design balances ticket order and mode, but cannot remove bias.",
    "Trial tickets are team-written (synthetic_team) and shorter than real service-desk tickets.",
    "The historical MTTR baseline is generated by the dataset generator (synthetic) and is "
    "shown for context only; it is not compared statistically with the trial.",
]


# =============================================================================================
# Parsing
# =============================================================================================
def parse_ts(value: str) -> float:
    """ISO-8601 (``Z`` or offset, or naive = UTC) → epoch seconds."""
    dt = datetime.fromisoformat(value.strip().replace("Z", "+00:00"))
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=UTC)
    return dt.timestamp()


def _truthy(v: Any) -> bool:
    return str(v).strip().lower() in ("1", "true", "yes", "y")


def read_events(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def observations(rows: Iterable[dict[str, str]], trial_ids: set[str]) -> list[dict[str, Any]]:
    """One observation per (participant, ticket, mode): TTD + the submitted decision.

    Practice rows and tickets outside the trial are dropped. The start is the first start
    event; the end is the first decision event after it. Pairs without both ends are skipped.
    """
    by_key: dict[tuple[str, str, str], list[dict[str, str]]] = defaultdict(list)
    for r in rows:
        mode = (r.get("mode") or "").strip()
        if mode not in START_EVENT or _truthy(r.get("practice")):
            continue
        if r.get("ticket_id") not in trial_ids:
            continue
        by_key[(r.get("participant") or "", r["ticket_id"], mode)].append(r)
    out = []
    for (participant, ticket, mode), evs in sorted(by_key.items()):
        evs.sort(key=lambda e: parse_ts(e["ts_utc"]))
        start = next((e for e in evs if e["event"] == START_EVENT[mode]), None)
        if start is None:
            continue
        t0 = parse_ts(start["ts_utc"])
        end = next(
            (e for e in evs if e["event"] == END_EVENT[mode] and parse_ts(e["ts_utc"]) >= t0), None
        )
        if end is None:
            continue
        conf = (end.get("confidence") or "").strip()
        out.append(
            {
                "participant": participant,
                "group": evs[0].get("group") or "",
                "ticket_id": ticket,
                "mode": mode,
                "ttd_s": parse_ts(end["ts_utc"]) - t0,
                "final_decision": end.get("final_decision") or "",
                "final_category": end.get("final_category") or "",
                "final_subcategory": end.get("final_subcategory") or "",
                "final_priority": end.get("final_priority") or "",
                "kb_or_incident_used": end.get("kb_or_incident_used") or "",
                "confidence": int(conf) if conf.isdigit() else None,
            }
        )
    return out


# =============================================================================================
# Scoring
# =============================================================================================
def _level(p: str) -> str | None:
    p = (p or "").strip()
    if p in PRIORITY_LEVELS:
        return p
    return PRIORITY_LEVEL.get(p.upper())


def score(obs: dict[str, Any], gold: dict[str, Any], incident_kbs: dict[str, set[str]]) -> dict:
    """Per-criterion correctness of one decision against ``trial_gold.json``."""
    lvl = _level(obs["final_priority"])
    used = {u.strip() for u in obs["kb_or_incident_used"].replace(";", ",").split(",") if u.strip()}
    used_kbs = {u for u in used if u.startswith("KB-")}
    for u in used - used_kbs:
        used_kbs |= incident_kbs.get(u, set())
    gold_kbs = set(gold.get("kb_ids") or [])
    if gold["decision"] == "escalate":
        kb_ok = obs["final_decision"] == "escalated"
    else:
        kb_ok = bool(used_kbs & gold_kbs) or (not gold_kbs and obs["final_decision"] == "escalated")
    res = {
        "category": obs["final_category"] == (gold.get("category") or ""),
        "subcategory": obs["final_subcategory"] == (gold.get("subcategory") or ""),
        "priority_within_one": lvl is not None and M.level_distance(lvl, gold["priority"]) <= 1,
        "kb_or_escalation": kb_ok,
    }
    res["all"] = all(res.values())
    return res


def _stats(values: Sequence[float]) -> dict[str, float | int | None]:
    if not values:
        return {"n": 0, "median_s": None, "mean_s": None, "p90_s": None}
    return {
        "n": len(values),
        "median_s": statistics.median(values),
        "mean_s": statistics.fmean(values),
        "p90_s": M.percentile(values, 90),
    }


def trial_summary(obs: list[dict[str, Any]], gold: dict[str, dict], incident_kbs: dict) -> dict:
    for o in obs:
        o["correct"] = score(o, gold[o["ticket_id"]], incident_kbs)
    by_mode = {m: [o for o in obs if o["mode"] == m] for m in ("manual", "assisted")}
    ttd = {m: _stats([o["ttd_s"] for o in v]) for m, v in by_mode.items()}
    med_m, med_a = ttd["manual"]["median_s"], ttd["assisted"]["median_s"]
    change = (med_a - med_m) / med_m * 100 if med_m and med_a is not None else None
    correctness = {
        m: {
            k: (sum(o["correct"][k] for o in v) / len(v) if v else None)
            for k in ("category", "subcategory", "priority_within_one", "kb_or_escalation", "all")
        }
        for m, v in by_mode.items()
    }
    confidence = {
        m: (statistics.fmean(c) if (c := [o["confidence"] for o in v if o["confidence"]]) else None)
        for m, v in by_mode.items()
    }
    # paired view: each participant's median TTD per mode
    per_participant: dict[str, dict[str, float]] = {}
    for p in sorted({o["participant"] for o in obs}):
        row = {}
        for m in ("manual", "assisted"):
            vals = [o["ttd_s"] for o in obs if o["participant"] == p and o["mode"] == m]
            if vals:
                row[m] = statistics.median(vals)
        per_participant[p] = row
    faster = [r["assisted"] < r["manual"] for r in per_participant.values() if len(r) == 2]
    per_ticket = {
        t: {
            m: statistics.median(v)
            for m in ("manual", "assisted")
            if (v := [o["ttd_s"] for o in obs if o["ticket_id"] == t and o["mode"] == m])
        }
        for t in sorted(gold)
    }
    return {
        "status": "ok",
        "participants": len(per_participant),
        "observations": len(obs),
        "ttd": ttd,
        "median_ttd_change_pct": change,
        "correctness": correctness,
        "self_reported_confidence_mean": confidence,
        "participants_faster_assisted": f"{sum(faster)}/{len(faster)}",
        "per_participant_median_ttd_s": per_participant,
        "per_ticket_median_ttd_s": per_ticket,
    }


# =============================================================================================
# Live and historical
# =============================================================================================
def live_metrics(db_path: Path) -> dict[str, Any]:
    """TTR (analysis.completed − ticket.submitted) and MTTR (ticket.resolved − submitted) from
    P3's ``ticket_events``; ``{"status": "no app.db"}`` if it doesn't exist yet."""
    if not db_path.exists():
        return {"status": "no app.db (run the API first)"}
    try:
        with sqlite3.connect(f"file:{db_path}?mode=ro", uri=True) as con:
            rows = con.execute(
                "SELECT ticket_id, analysis_id, event, ts_utc, mode FROM ticket_events"
            ).fetchall()
    except sqlite3.Error as exc:
        return {"status": f"ticket_events unavailable: {exc}"}
    first: dict[tuple[str, str], float] = {}
    for tid, _aid, event, ts, _mode in rows:
        key = (tid, event)
        t = parse_ts(ts)
        if key not in first or t < first[key]:
            first[key] = t
    tickets = {tid for tid, *_ in rows}
    ttr = [
        first[(t, "analysis.completed")] - first[(t, "ticket.submitted")]
        for t in tickets
        if (t, "analysis.completed") in first and (t, "ticket.submitted") in first
    ]
    mttr = [
        first[(t, "ticket.resolved")] - first[(t, "ticket.submitted")]
        for t in tickets
        if (t, "ticket.resolved") in first and (t, "ticket.submitted") in first
    ]
    return {
        "status": "ok",
        "tickets": len(tickets),
        "ttr_s": {"n": len(ttr), "p50": M.percentile(ttr, 50), "p95": M.percentile(ttr, 95)},
        "mttr_s": _stats(mttr),
    }


def historical_baseline(root: Path | None = None) -> dict[str, Any]:
    """Median/mean resolution hours from the generator's timestamps — SYNTHETIC, context only."""
    rows = read_json(repo_path("tickets_enriched", root))
    hours: dict[str, dict[str, list[float]]] = {
        "category": defaultdict(list),
        "priority": defaultdict(list),
    }
    for r in rows:
        if r.get("opened_ts") and r.get("resolved_ts"):
            h = (r["resolved_ts"] - r["opened_ts"]) / 3600
            hours["category"][r["category"]].append(h)
            hours["priority"][PRIORITY_LEVEL.get(r["priority"], r["priority"])].append(h)
    return {
        "label": "SYNTHETIC (dataset generator timestamps) - context only",
        **{
            dim: {
                k: {"n": len(v), "median_h": statistics.median(v), "mean_h": statistics.fmean(v)}
                for k, v in sorted(groups.items())
            }
            for dim, groups in hours.items()
        },
    }


